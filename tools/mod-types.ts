// Writes types/mod.d.ts, the types of "yellowcode/mod" for mods type-checked outside this repo. With --check it only
// compares, and fails when the committed file is stale.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

const repo = join(import.meta.dir, "..")
const target = join(repo, "types/mod.d.ts")
// In the order a reader meets them: the version, the kit, then the API.
const FILES = ["version", "kit", "api"]

const out = mkdtempSync(join(tmpdir(), "yellowcode-mod-types-"))
const config = join(out, "tsconfig.json")
writeFileSync(
  config,
  JSON.stringify({
    extends: join(repo, "tsconfig.json"),
    include: [],
    files: [join(repo, "src/mods/api.ts")],
    compilerOptions: {
      noEmit: false,
      declaration: true,
      emitDeclarationOnly: true,
      outDir: join(out, "dts"),
      rootDir: repo,
      typeRoots: [join(repo, "node_modules/@types")],
      // With api.ts alone as the root a few UI files lose context they get in the full program, which `bun run
      // typecheck` checks; only the declarations matter here.
      noImplicitAny: false,
    },
  }),
)
const tsc = Bun.spawnSync(["bunx", "tsc", "-p", config], { cwd: repo, stdout: "inherit", stderr: "inherit" })
if (tsc.exitCode !== 0) {
  rmSync(out, { recursive: true, force: true })
  process.exit(tsc.exitCode ?? 1)
}

// Imports of other files of the API go; the names taken from packages are merged into one import per package.
const imports = new Map<string, Set<string>>()
const bodies = FILES.map((name) => {
  const text = readFileSync(join(out, "dts/src/mods", `${name}.d.ts`), "utf8")
  const lines = text.split("\n").filter((line) => {
    if (/^(import|export) .* from "\.{1,2}\//.test(line)) return false
    const taken = /^import (?:type )?\{([^}]*)\} from "([^"]+)";?$/.exec(line)
    if (taken) {
      const names = imports.get(taken[2] ?? "") ?? new Set<string>()
      for (const part of (taken[1] ?? "").split(",")) if (part.trim()) names.add(part.replace("type ", "").trim())
      imports.set(taken[2] ?? "", names)
      return false
    }
    if (line.startsWith("import ")) throw new Error(`unexpected import in ${name}.d.ts: ${line}`)
    return line.trim() !== "export {};"
  })
  return lines.join("\n").trim()
})
rmSync(out, { recursive: true, force: true })

const importLines = [...imports]
  .toSorted(([a], [b]) => a.localeCompare(b))
  .map(([from, names]) => `import type { ${[...names].toSorted().join(", ")} } from "${from}";`)
const raw = `// The types of "yellowcode/mod". Generated by tools/mod-types.ts from src/mods; do not edit.\n${importLines.join("\n")}\n\n${bodies.join("\n\n")}\n`
// In the repo's own style, so the format check passes.
const formatted = Bun.spawnSync(["bunx", "oxfmt", `--stdin-filepath=${target}`], { cwd: repo, stdin: Buffer.from(raw) })
if (formatted.exitCode !== 0) throw new Error(`oxfmt failed: ${formatted.stderr.toString()}`)
const file = formatted.stdout.toString()

if (process.argv.includes("--check")) {
  let committed = ""
  try {
    committed = readFileSync(target, "utf8")
  } catch {}
  if (committed !== file) {
    console.error("types/mod.d.ts is stale; run `bun run types`")
    process.exit(1)
  }
} else writeFileSync(target, file)
